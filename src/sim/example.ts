export function buildExample(sim: Sim) {
  for (const [k, x, y, r] of EXAMPLE_MACHINES) {
    if (!sim.canPlace(k, x, y)) throw new Error(`示例工厂冲突: ${k} @ ${x},${y}`);
    sim.place(k, x, y, r);
  }
  for (const [x, y, r, turbo] of EXAMPLE_BELTS) {
    const kind: EntKind = turbo ? 'turbo' : 'belt';
    if (!sim.canPlace(kind, x, y)) throw new Error(`示例工厂传送带冲突: @ ${x},${y}`);
    sim.place(kind, x, y, r);
  }
}
